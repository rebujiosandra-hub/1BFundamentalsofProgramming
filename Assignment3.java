public class Assignment3 {
    public static void main () {
        // String data type - stores text (name is made up of letters)
        String firstName = "Sandra Mae";

        // String data type - stores text
        String lastName = "Rebujio";

        // String data type - stores text (address is a mix of words/numbers)
        String address = "Binalonan";

        // String data type - used instead of int because mobile numbers
        // can start with 0 and we don't perform math on them
        String mobileNumber = "09667920974";

        // int data type - stores whole numbers (age has no decimal)
        int age = 17;

        // double data type - stores decimal numbers (age has no decimal)
        double gwa = 96.0;

        // Display all the stored information using println
        System.out.println("Firstname: " + firstName);
        System.out.println("Lastname: " + lastName);
        System.out.println("Address: " + address);
        System.out.println("Mobile Number: " + mobileNumber);
        System.out.println("Age: " + age);
        System.out.println("GWA: " + gwa);
   }
}